"""Create a README comparison plate from two original competition maps.

This script only crops and arranges the source rasters. It does not reconstruct
boundaries, classifications or spatial values.
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


PROJECT_ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = PROJECT_ROOT / "outputs" / "maps" / "source"
OUTPUT_PATH = PROJECT_ROOT / "outputs" / "maps" / "coupling_coordination_2010_2022.png"


def font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    windows_font = Path("C:/Windows/Fonts/arialbd.ttf" if bold else "C:/Windows/Fonts/arial.ttf")
    if windows_font.exists():
        return ImageFont.truetype(str(windows_font), size=size)
    return ImageFont.load_default()


def prepare(path: Path) -> Image.Image:
    image = Image.open(path).convert("RGB")
    cropped = image.crop((25, 70, 770, 955))
    return cropped.resize((708, 841), Image.Resampling.LANCZOS)


def main() -> None:
    panels = [
        prepare(SOURCE_DIR / "coupling_coordination_2010.jpg"),
        prepare(SOURCE_DIR / "coupling_coordination_2022.jpg"),
    ]
    canvas = Image.new("RGB", (1500, 1010), "white")
    draw = ImageDraw.Draw(canvas)
    draw.text((42, 25), "Coupling coordination across Henan cities", fill="#242424", font=font(38, bold=True))
    draw.text((42, 70), "Original competition maps, 2010 and 2022", fill="#666666", font=font(22))
    draw.text((42, 112), "a  2010", fill="#242424", font=font(24, bold=True))
    draw.text((770, 112), "b  2022", fill="#242424", font=font(24, bold=True))
    canvas.paste(panels[0], (30, 145))
    canvas.paste(panels[1], (760, 145))
    draw.text((42, 987), "Static source figures; classifications and boundaries are not regenerated by the public workflow.", fill="#6A6A6A", font=font(15))
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    canvas.save(OUTPUT_PATH, optimize=True)
    print(OUTPUT_PATH.relative_to(PROJECT_ROOT))


if __name__ == "__main__":
    main()
